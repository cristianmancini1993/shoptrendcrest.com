def patch_json(stem: str) -> None:
    path = LOC / LOCALE_FILES[stem]
    data = json.loads(path.read_text(encoding="utf-8"))
    data.update(DRYER[stem])
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"patched {path.name}")


def sync_it_py() -> None:
    text = IT_PY.read_text(encoding="utf-8")
    it = DRYER["it"]
    for key, val in it.items():
        val_esc = val.replace("\\", "\\\\").replace('"', '\\"')
        pattern = rf'  "{re.escape(key)}": "[^"]*(?:\\.[^"]*)*",'
        repl = f'  "{key}": "{val_esc}",'
        new_text, n = re.subn(pattern, repl, text, count=1)
        if n == 0:
            raise SystemExit(f"missing key in _linvo_it_strings.py: {key}")
        text = new_text
    IT_PY.write_text(text, encoding="utf-8")
    print("synced _linvo_it_strings.py")


def main() -> None:
    for stem in LOCALE_FILES:
        patch_json(stem)
    sync_it_py()


