def marketing_for(lang: str) -> dict[str, str]:
    if lang in ("cs", "sk", "sl", "hr"):
        base = pl_derived(lang)
    else:
        base = ro_derived(lang)
    base.update(MANUAL.get(lang, {}))
    return base


def load_copy() -> dict:
    spec = importlib.util.spec_from_file_location("_trimex_copy_data", COPY_PATH)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod.COPY


def build_copy_patches(copy: dict) -> dict[str, dict[str, str]]:
    patch_keys = list(copy["pl"].keys())
    marketing_keys = patch_keys[patch_keys.index("title") :]
    patches: dict[str, dict[str, str]] = {}
    for lang in LANGS:
        merged = {k: copy[lang][k] for k in patch_keys}
        mkt = marketing_for(lang)
        for k in marketing_keys:
            merged[k] = mkt[k]
        merged.update({k: v for k, v in MANUAL.get(lang, {}).items() if k in patch_keys})
        patches[lang] = {k: merged[k] for k in patch_keys}
    return patches


def emit_copy_patches_py(patches: dict[str, dict[str, str]]) -> str:
    body = pprint.pformat(patches, width=120, sort_dicts=False)
    return (
        "# -*- coding: utf-8 -*-\n"
        '"""Native TRIMEX copy patches for cs, hu, lv, sl, hr, sk (keys match pl locale)."""\n\n'
        f"COPY_PATCHES = {body}\n"
    )


def main() -> None:
    copy = load_copy()
    patches = build_copy_patches(copy)
    OUT_PATH.write_text(emit_copy_patches_py(patches), encoding="utf-8")
    print(f"Wrote {OUT_PATH} ({len(patches)} locales)")


if __name__ == "__main__":
    main()
